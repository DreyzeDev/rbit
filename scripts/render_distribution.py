#!/usr/bin/env python3
"""Fill the package-manager templates in `distribution/` for a release.

    python scripts/render_distribution.py --version 1.7.0 --sdist dist/rbit-1.7.0.tar.gz \
        [--windows-zip rbit-1.7.0-windows-x64.zip] --out dist/distribution

Homebrew needs only the sdist the release already builds. Scoop and winget install a Windows
zip, which the release workflow does not build yet: they are rendered only when --windows-zip is
given, so a manifest with a made-up hash is never produced.
"""

from __future__ import annotations

import argparse
import hashlib
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DIST = ROOT / "distribution"
PLACEHOLDER = "<SHA256-PLACEHOLDER>"


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(1 << 20), b""):
            digest.update(block)
    return digest.hexdigest()


def render_homebrew(version: str, sdist: Path) -> str:
    text = (DIST / "rbit.rb").read_text(encoding="utf-8")
    text = text.replace("<VERSION>", version).replace(PLACEHOLDER, sha256(sdist))
    # the instructions at the top describe the template, not the finished formula
    return re.sub(r"\A(?:#.*\n)+\n", "# Generated by scripts/render_distribution.py\n\n", text)


def render_scoop(version: str, zip_path: Path) -> str:
    text = (DIST / "rbit.scoop.json").read_text(encoding="utf-8")
    text = text.replace('"version": "0.0.0"', f'"version": "{version}"')
    text = text.replace("v0.0.0/rbit-0.0.0-", f"v{version}/rbit-{version}-").replace(PLACEHOLDER, sha256(zip_path))
    return re.sub(r'\s*"Placeholder manifest[^\n]*\n', "\n", text).replace('"notes": [\n\n', '"notes": [\n')


def render_winget(version: str, zip_path: Path) -> str:
    text = (DIST / "rbit.winget").read_text(encoding="utf-8")
    text = text.replace("PackageVersion: 0.0.0", f"PackageVersion: {version}")
    text = text.replace("v0.0.0/rbit-0.0.0-", f"v{version}/rbit-{version}-")
    return text.replace(PLACEHOLDER, sha256(zip_path).upper())


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--version", required=True, help="release version without the leading v")
    parser.add_argument("--sdist", required=True, type=Path, help="the built rbit-<version>.tar.gz")
    parser.add_argument("--windows-zip", type=Path, help="rbit-<version>-windows-x64.zip (enables scoop/winget)")
    parser.add_argument("--out", required=True, type=Path)
    args = parser.parse_args(argv)

    if not re.fullmatch(r"\d+\.\d+\.\d+(?:[-.]?(?:rc|a|b)\d+)?", args.version):
        print(f"not a release version: {args.version!r}", file=sys.stderr)
        return 2
    if not args.sdist.is_file():
        print(f"sdist not found: {args.sdist}", file=sys.stderr)
        return 2
    args.out.mkdir(parents=True, exist_ok=True)
    (args.out / "rbit.rb").write_text(render_homebrew(args.version, args.sdist), encoding="utf-8")
    written = ["rbit.rb"]
    if args.windows_zip:
        if not args.windows_zip.is_file():
            print(f"windows zip not found: {args.windows_zip}", file=sys.stderr)
            return 2
        (args.out / "rbit.scoop.json").write_text(render_scoop(args.version, args.windows_zip), encoding="utf-8")
        (args.out / "rbit.winget").write_text(render_winget(args.version, args.windows_zip), encoding="utf-8")
        written += ["rbit.scoop.json", "rbit.winget"]
    for name in written:
        if PLACEHOLDER in (args.out / name).read_text(encoding="utf-8") or "<VERSION>" in (args.out / name).read_text(encoding="utf-8"):
            print(f"placeholder left in {name}", file=sys.stderr)
            return 1
    print("rendered: " + ", ".join(written))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
